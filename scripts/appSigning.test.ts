import { spawnSync } from 'node:child_process';
import {
    createPrivateKey,
    createPublicKey,
    generateKeyPairSync,
    X509Certificate,
    type KeyObject
} from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { afterAll, beforeAll, describe, expect, it } from 'vitest';

import {
    desktopAssets,
    exportPkcs12,
    insertSigningConfig,
    loadSigningIdentity,
    signFile,
    verifyFile
} from './app-signing';

const directory = fs.mkdtempSync(
    path.join(os.tmpdir(), 'vrcx-0-signing-test-')
);
const secret = path.join(directory, 'SECRET');
const trusted = path.join(directory, 'public');
const settings = path.join(directory, 'local.json');
const password = 'fixture-only-password';
let privateKey: KeyObject;
let publicKey: KeyObject;
let encryptedPem: Buffer;

beforeAll(() => {
    fs.mkdirSync(secret, { mode: 0o700 });
    fs.mkdirSync(trusted);
    const pair = generateKeyPairSync('rsa', { modulusLength: 2048 });
    privateKey = pair.privateKey;
    publicKey = pair.publicKey;
    encryptedPem = Buffer.from(
        privateKey.export({
            type: 'pkcs8',
            format: 'pem',
            cipher: 'aes-256-cbc',
            passphrase: password
        })
    );
    fs.writeFileSync(path.join(secret, 'identity.key.pem'), encryptedPem, {
        mode: 0o600
    });
    fs.writeFileSync(path.join(secret, 'password.txt'), `${password}\n`, {
        mode: 0o600
    });
    fs.writeFileSync(
        path.join(trusted, 'release-public-key.pem'),
        publicKey.export({ type: 'spki', format: 'pem' })
    );
    fs.writeFileSync(settings, JSON.stringify({ directory }));
    const certificate = spawnSync(
        'openssl',
        [
            'req',
            '-new',
            '-x509',
            '-key',
            path.join(secret, 'identity.key.pem'),
            '-passin',
            `file:${path.join(secret, 'password.txt')}`,
            '-days',
            '1',
            '-subj',
            '/O=Signing Fixture/CN=Signing Fixture',
            '-addext',
            'basicConstraints=critical,CA:FALSE',
            '-addext',
            'extendedKeyUsage=codeSigning',
            '-out',
            path.join(trusted, 'identity.cert.pem')
        ],
        { encoding: 'utf8' }
    );
    expect(certificate.status, certificate.stderr).toBe(0);
});

afterAll(() => {
    fs.rmSync(directory, { recursive: true, force: true });
});

function artifact(name: string, contents = 'original release bytes'): string {
    const file = path.join(directory, name);
    fs.writeFileSync(file, contents);
    return file;
}

describe('release signing', () => {
    it('signs exact bytes interoperably with OpenSSL and leaves updater signatures intact', async () => {
        const file = artifact('Application with spaces.AppImage');
        fs.writeFileSync(`${file}.sig`, 'existing Tauri updater signature');
        await signFile(file, privateKey);
        await expect(verifyFile(file, publicKey)).resolves.toBeUndefined();
        const result = spawnSync(
            'openssl',
            [
                'dgst',
                '-sha256',
                '-verify',
                path.join(trusted, 'release-public-key.pem'),
                '-signature',
                `${file}.nn-signature`,
                file
            ],
            { encoding: 'utf8' }
        );
        expect(result.status, result.stderr).toBe(0);
        expect(result.stdout).toContain('Verified OK');
        expect(fs.readFileSync(`${file}.sig`, 'utf8')).toBe(
            'existing Tauri updater signature'
        );
    });

    it('verifies signatures generated by the generic OpenSSL kit format', async () => {
        const file = artifact('Application.dmg');
        const result = spawnSync(
            'openssl',
            [
                'dgst',
                '-sha256',
                '-sign',
                path.join(secret, 'identity.key.pem'),
                '-passin',
                `file:${path.join(secret, 'password.txt')}`,
                '-out',
                `${file}.nn-signature`,
                file
            ],
            { encoding: 'utf8' }
        );
        expect(result.status, result.stderr).toBe(0);
        await expect(verifyFile(file, publicKey)).resolves.toBeUndefined();
    });

    it('rejects modified artifacts and refuses to replace their existing signatures', async () => {
        const file = artifact('tampered.exe');
        await signFile(file, privateKey);
        const original = fs.readFileSync(`${file}.nn-signature`);
        fs.appendFileSync(file, 'tampered');
        await expect(verifyFile(file, publicKey)).rejects.toThrow(
            'verification failed'
        );
        await expect(signFile(file, privateKey)).rejects.toThrow(
            'different signature'
        );
        expect(fs.readFileSync(`${file}.nn-signature`)).toEqual(original);
    });

    it('rejects modified signatures and a different verification key', async () => {
        const file = artifact('invalid-signature.exe');
        await signFile(file, privateKey);
        const other = generateKeyPairSync('rsa', { modulusLength: 2048 });
        await expect(verifyFile(file, other.publicKey)).rejects.toThrow(
            'verification failed'
        );
        const signature = fs.readFileSync(`${file}.nn-signature`);
        signature[signature.length - 1] ^= 1;
        fs.writeFileSync(`${file}.nn-signature`, signature);
        await expect(verifyFile(file, publicKey)).rejects.toThrow(
            'verification failed'
        );
    });

    it('can be rerun for unchanged bytes and verifies after artifact renaming', async () => {
        const file = artifact('installer-setup.exe');
        await signFile(file, privateKey);
        await expect(signFile(file, privateKey)).resolves.toBeUndefined();
        const renamed = path.join(directory, 'versioned-installer.exe');
        fs.renameSync(file, renamed);
        fs.renameSync(`${file}.nn-signature`, `${renamed}.nn-signature`);
        await expect(verifyFile(renamed, publicKey)).resolves.toBeUndefined();
    });
});

describe('signing identity configuration', () => {
    it('loads the encrypted identity from ignored local settings', () => {
        const identity = loadSigningIdentity({}, settings, trusted);
        expect(
            createPublicKey(identity!.key).export({
                type: 'spki',
                format: 'der'
            })
        ).toEqual(publicKey.export({ type: 'spki', format: 'der' }));
    });

    it('loads CI secrets without requiring the local kit', () => {
        const identity = loadSigningIdentity(
            {
                NN_SIGNING_KEY_PEM_BASE64: encryptedPem.toString('base64'),
                NN_SIGNING_PASSWORD: password,
                NN_SIGNING_REQUIRED: '1'
            },
            path.join(directory, 'absent-settings.json'),
            trusted
        );
        expect(identity).not.toBeNull();
    });

    it('allows contributor builds without keys but fails required release signing', () => {
        const missing = path.join(directory, 'absent-settings.json');
        expect(loadSigningIdentity({}, missing, trusted)).toBeNull();
        expect(() =>
            loadSigningIdentity({ NN_SIGNING_REQUIRED: '1' }, missing, trusted)
        ).toThrow('required for release packages');
        expect(() =>
            loadSigningIdentity(
                { NN_SIGNING_PASSWORD: password },
                missing,
                trusted
            )
        ).toThrow('Both NN_SIGNING');
    });

    it('rejects wrong passwords and a valid private key that does not match the pin', () => {
        const environment = {
            NN_SIGNING_KEY_PEM_BASE64: encryptedPem.toString('base64'),
            NN_SIGNING_PASSWORD: 'incorrect'
        };
        expect(() =>
            loadSigningIdentity(environment, settings, trusted)
        ).toThrow('Unable to unlock');
        const other = generateKeyPairSync('rsa', { modulusLength: 2048 });
        const encoded = other.privateKey.export({
            type: 'pkcs8',
            format: 'pem',
            cipher: 'aes-256-cbc',
            passphrase: password
        });
        expect(() =>
            loadSigningIdentity(
                {
                    NN_SIGNING_KEY_PEM_BASE64:
                        Buffer.from(encoded).toString('base64'),
                    NN_SIGNING_PASSWORD: password
                },
                settings,
                trusted
            )
        ).toThrow('pinned public key');
    });

    it('does not disclose the configured private location on a read failure', () => {
        expect(() =>
            loadSigningIdentity(
                {
                    NN_APP_SIGNING_HOME: path.join(
                        directory,
                        'missing-private-location'
                    )
                },
                settings,
                trusted
            )
        ).toThrow(
            /^Unable to read the configured local app signing identity\.$/
        );
    });
});

describe('packaging integration', () => {
    it.each([
        ['darwin', 'pbeWithSHA1And3-KeyTripleDES-CBC', 'sha1'],
        ['win32', 'AES-256-CBC', 'sha256']
    ] as const)(
        'exports a password-protected %s identity with its original key and certificate',
        (platform, encryption, digest) => {
            const output = path.join(directory, `${platform}.p12`);
            const environment = {
                ...process.env,
                NN_SIGNING_OPENSSL: process.env.NN_SIGNING_OPENSSL || 'openssl',
                NN_SIGNING_PASSWORD: password
            };
            exportPkcs12(
                path.join(secret, 'identity.key.pem'),
                path.join(trusted, 'identity.cert.pem'),
                output,
                password,
                platform,
                environment
            );
            const inspect = spawnSync(
                environment.NN_SIGNING_OPENSSL,
                [
                    'pkcs12',
                    '-in',
                    output,
                    '-passin',
                    'env:NN_SIGNING_PASSWORD',
                    '-info',
                    '-noout'
                ],
                { env: environment, encoding: 'utf8' }
            );
            expect(inspect.status, inspect.stderr).toBe(0);
            expect(inspect.stderr).toContain(
                `MAC: ${digest}, Iteration 100000`
            );
            expect(inspect.stderr).toContain(encryption);
            const decoded = spawnSync(
                environment.NN_SIGNING_OPENSSL,
                [
                    'pkcs12',
                    '-in',
                    output,
                    '-passin',
                    'env:NN_SIGNING_PASSWORD',
                    '-nodes'
                ],
                { env: environment, encoding: 'utf8' }
            );
            expect(decoded.status, decoded.stderr).toBe(0);
            expect(
                createPublicKey(createPrivateKey(decoded.stdout)).export({
                    type: 'spki',
                    format: 'der'
                })
            ).toEqual(publicKey.export({ type: 'spki', format: 'der' }));
            expect(new X509Certificate(decoded.stdout).raw).toEqual(
                new X509Certificate(
                    fs.readFileSync(path.join(trusted, 'identity.cert.pem'))
                ).raw
            );
            const wrongPassword = spawnSync(
                environment.NN_SIGNING_OPENSSL,
                [
                    'pkcs12',
                    '-in',
                    output,
                    '-passin',
                    'env:NN_SIGNING_PASSWORD',
                    '-noout'
                ],
                {
                    env: { ...environment, NN_SIGNING_PASSWORD: 'incorrect' },
                    encoding: 'utf8'
                }
            );
            expect(wrongPassword.status).not.toBe(0);
        }
    );

    it('finds downloadable packages without signing updater files, keys, or app internals', () => {
        const packages = fs.mkdtempSync(path.join(directory, 'packages-'));
        for (const file of [
            'app.exe',
            'app.AppImage',
            'app.dmg',
            'app.app.tar.gz',
            'app.exe.sig',
            'app.exe.nn-signature',
            'public.pem',
            'version_manifest.json'
        ]) {
            fs.writeFileSync(path.join(packages, file), 'fixture');
        }
        fs.mkdirSync(path.join(packages, 'app.app'));
        fs.writeFileSync(
            path.join(packages, 'app.app', 'nested.exe'),
            'fixture'
        );
        expect(
            desktopAssets(packages)
                .map((file) => path.basename(file))
                .sort()
        ).toEqual(['app.AppImage', 'app.app.tar.gz', 'app.dmg', 'app.exe']);
    });

    it('adds native signing after variant overrides and before Cargo arguments', () => {
        const override = {
            bundle: {
                windows: {
                    signCommand: { cmd: 'node', args: ['signer', '%1'] }
                }
            }
        };
        const args = insertSigningConfig(
            ['build', '--config', 'variant.json', '--', '--timings'],
            override
        );
        expect(args).toEqual([
            'build',
            '--config',
            'variant.json',
            '--config',
            JSON.stringify(override),
            '--',
            '--timings'
        ]);
        expect(
            insertSigningConfig(['bundle', '--bundles', 'app,dmg'], override)
        ).toEqual([
            'bundle',
            '--bundles',
            'app,dmg',
            '--config',
            JSON.stringify(override)
        ]);
    });
});
